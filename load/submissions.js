// k6 — simulate 2,000 teams submitting metadata in 10 minutes (PS2).
// Files themselves go direct-to-S3; this stresses the API control plane.
// Run: k6 run load/submissions.js  (requires seeded users + tokens)
import http from 'k6/http';
import { check } from 'k6';

export const options = {
  scenarios: {
    deadline_crush: {
      executor: 'constant-arrival-rate',
      rate: 200,          // 200 submissions/min → 2,000 in 10 min
      timeUnit: '1m',
      duration: '10m',
      preAllocatedVUs: 100,
      maxVUs: 300,
    },
  },
  thresholds: {
    http_req_duration: ['p(95)<300'],
    http_req_failed: ['rate<0.02'],
  },
};

const BASE = __ENV.BASE_URL || 'http://localhost:4000';
const TOKENS = (__ENV.TOKENS || '').split(',').filter(Boolean);

export function setup() {
  // In CI/demo: tokens are pre-generated by `npm run seed:tokens`.
  // For local smoke runs without tokens, register on the fly.
  if (TOKENS.length === 0) {
    const email = `k6-${Date.now()}@load.dev`;
    const res = http.post(`${BASE}/api/auth/register`, JSON.stringify({
      email, password: 'password123', displayName: 'k6 user',
    }), { headers: { 'Content-Type': 'application/json' } });
    return { token: JSON.parse(res.body).accessToken };
  }
  return { tokens: TOKENS };
}

export default function (data) {
  const token = Array.isArray(data.tokens)
    ? data.tokens[Math.floor(Math.random() * data.tokens.length)]
    : data.token;
  const res = http.post(`${BASE}/api/submissions`, JSON.stringify({
    hackathonId: __ENV.HACKATHON_ID,
    teamId: __ENV.TEAM_ID,
    title: `Submission ${__ITER}`,
    links: ['https://example.com'],
  }), { headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${token}` } });
  check(res, { 'created': (r) => r.status === 201 || r.status === 409 });
}
